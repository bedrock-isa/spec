DOMAINS = {
    "finite_abs_le_pi_over_4": r"finite x with abs(x) $\leq$ pi / 4 after DAZ",
    "finite_abs_le_one": r"finite x with abs(x) $\leq$ 1 after DAZ",
    "finite_or_signed_infinity": r"all finite values and signed infinity after DAZ",
    "positive_or_positive_infinity_zero_dz": (
        r"positive finite values and positive infinity after DAZ; signed zero is the DZ boundary"
    ),
    "finite_ge_minus_one_or_positive_infinity_minus_one_dz": (
        r"finite x $\geq -1$ and positive infinity after DAZ; $-1$ is the DZ boundary"
    ),
}


def render_fptransa_contracts(data: dict[str, Any]) -> str:
    rows = []
    for item in data["fptransa_accuracy_contracts"]:
        reference = REFERENCE_FUNCTIONS[item["function"]]
        if item.get("reference_qualifier") == "radians":
            reference += " in radians"
        max_ulp = item["max_ulp"]
        bound = rf"S $\leq$ {int(max_ulp['S'])} ULP; D $\leq$ {int(max_ulp['D'])} ULP"
        mnemonic = str(item["mnemonic"])
        rows.append(
            [
                tex_code(f"0x{int(item['id']):04x}"),
                rf"\hyperref[instr:{mnemonic.lower()}]{{{tex_code(mnemonic)}}}",
                reference,
                DOMAINS[item["domain"]],
                bound,
            ]
        )
    return latex_longtable(
        ["Contract ID", "Mnemonic", "Reference", "Domain", "ISA maximum"],
        rows,
        ["0.72in", "0.78in", "1.20in", "2.05in", "0.90in"],
        "FPTRANSA Accuracy Contracts",
    )


def render_event_frames(data: dict[str, Any]) -> str:
    rows = []
    for item in data["event_frames"]["types"]:
        last_slot = "none" if item["last_slot"] == "none" else tex_escape(item["last_slot"])
        rows.append(
            [
                f"0x{int(item['code']):x}",
                tex_escape(item["name"]),
                str(int(item["payload_bytes"])),
                str(int(item["allocated_payload_bytes"])),
                str(int(item["total_bytes"])),
                str(int(item["total_bytes"]) // 8),
                last_slot,
            ]
        )
    frame_table = latex_longtable(
        ["Code", "Type", "Payload", "Allocated", "Total", "Size", "Last slot"],
        rows,
        ["0.42in", "0.82in", "0.68in", "0.78in", "0.88in", "0.62in", "1.00in"],
        "Architectural Event Frame Types and Sizes",
    )
    assignment_rows = []
    for item in data["event_frames"]["assignments"]:
        if "events" in item:
            delivered = code_list(item["events"])
        else:
            delivered = "interrupt and NMI"
        assignment_rows.append([delivered, tex_escape(item["frame_type"])])
    assignment_table = latex_longtable(
        ["Delivered event", "Frame type"],
        assignment_rows,
        ["3.75in", "1.45in"],
        "Event-to-Frame-Type Assignment",
    )
    return frame_table + "\n" + assignment_table


def operand_range(spec: dict[str, Any], range_from: str) -> str:
    width = int(spec["field_width"])
    if range_from == "declared_values":
        values = [int(item["value"]) for item in spec.get("values", [])]
        if not values:
            raise ValueError("declared_values range requires enum values")
        return f"{min(values)}..{max(values)}"
    if range_from != "field_width":
        raise ValueError(f"unknown operand range source: {range_from}")
    return f"0..{(1 << width) - 1}"


def render_immediate_operands(data: dict[str, Any]) -> str:
    operands = load_mapping(OPERANDS_SOURCE)["operand_types"]
    rows = []
    for item in data["immediate_operand_interpretation"]:
        operand_type = str(item["operand_type"])
        spec = operands[operand_type]
        rows.append(
            [
                tex_code(operand_type),
                str(int(spec["field_width"])),
                tex_escape(item["value_kind"]),
                tex_escape(operand_range(spec, item["range_from"])),
                tex_escape(item["extension"]),
                tex_escape(item["applies_when"]),
            ]
        )
    return latex_longtable(
        ["Operand", "Bits", "Value", "Range", "Extension", "Applies When"],
        rows,
        ["0.95in", "0.38in", "0.62in", "0.62in", "0.90in", "1.70in"],
        "Immediate Operand Interpretation",
    )


def render_reset_state(data: dict[str, Any]) -> str:
    reset_values = {
        "zero": "0",
        "invalid": "invalid",
        "platform_supplied_cold_preserved_warm": "platform supplied on cold reset; preserved by warm RESET",
    }
    rows = []
    for item in data["reset_state"]:
        if "state_pairs" in item:
            state = ", ".join(f"{left}:{right}" for left, right in item["state_pairs"])
        else:
            names = [str(value) for value in item["state"]]
            state = ", ".join(names).replace("hidden_current_edepth", "hidden_current_edepth")
            state = state.replace("hidden_current_event_stack_level", "hidden current event stack level")
        rows.append([tex_escape(state), tex_escape(reset_values[item["value"]])])
    return latex_longtable(
        ["State", "Reset Value"],
        rows,
        ["2.00in", "2.40in"],
        "Architectural Reset State",
    )


def render_atomic_orders(data: dict[str, Any]) -> str:
    effects = {
        "atomicity_only": "Atomicity only. No ordering is imposed on unrelated memory operations.",
        "acquire": "Later memory operations by the same hardware thread are ordered after the atomic operation.",
        "release": "Earlier memory operations by the same hardware thread are ordered before the atomic operation.",
        "acquire_release": "Applies both acquire and release ordering.",
        "sequentially_consistent": (
            "Applies acquire-release ordering and participates in the single global sequentially consistent order."
        ),
    }
    rows = [
        [tex_code(item["selector"]), tex_code(item["code"]), tex_escape(effects[item["effect"]])]
        for item in data["atomic_memory_orders"]
    ]
    return latex_tabular(
        ["Selector", "Code", "Architectural Ordering Effect"],
        rows,
        ["0.95in", "0.45in", "4.00in"],
        "Atomic Memory-Order Selectors",
    )


def output_files(data: dict[str, Any]) -> dict[Path, str]:
    performance_table = render_performance_counters(data)
    if not RDPMC_TEMPLATE.is_file():
        raise ValueError(f"missing RDPMC template: {RDPMC_TEMPLATE}")
    rdpmc_details = RDPMC_TEMPLATE.read_text(encoding="utf-8")
    marker = "@STANDARD_PERFORMANCE_COUNTERS_TABLE@"
    if rdpmc_details.count(marker) != 1:
        raise ValueError(f"{RDPMC_TEMPLATE}: expected exactly one {marker}")
    rdpmc_details = rdpmc_details.replace(marker, performance_table.rstrip())

    return {
        GENERATED_DIR / "reserved_field_defaults.tex": generated(render_reserved_defaults(data)),
        GENERATED_DIR / "cpuid_class_leaf_directory.tex": generated(render_cpuid_directory(data)),
        GENERATED_DIR / "control_register_selectors.tex": generated(render_control_registers(data)),
        GENERATED_DIR / "page_fault_causes.tex": generated(render_exception_causes(data, "PAGE_FAULT")),
        GENERATED_DIR / "illegal_instruction_causes.tex": generated(
            render_exception_causes(data, "ILLEGAL_INSTRUCTION")
        ),
        GENERATED_DIR / "invalid_control_state_causes.tex": generated(
            render_exception_causes(data, "INVALID_CONTROL_STATE")
        ),
        GENERATED_DIR / "immediate_operand_interpretation.tex": generated(
            render_immediate_operands(data)
        ),
        GENERATED_DIR / "atomic_memory_order_selectors.tex": generated(render_atomic_orders(data)),
        FRAGMENT_DIR / "fptransa_accuracy_contracts.tex": generated(render_fptransa_contracts(data)),
        FRAGMENT_DIR / "frame_type_table.tex": generated(render_event_frames(data)),
        FRAGMENT_DIR / "reset_state_table.tex": generated(render_reset_state(data)),
        RDPMC_OUTPUT: generated(rdpmc_details),
    }


def generate(*, check: bool = False) -> list[Path]:
    data = load_mapping(SOURCE)
    validate_manifest(data)
    outputs = output_files(data)
    stale: list[Path] = []
    for path, content in outputs.items():
        if check:
            if not path.is_file() or path.read_text(encoding="utf-8") != content:
                stale.append(path)
            continue
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(content, encoding="utf-8")
    return stale


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--check",
        action="store_true",
        help="validate the manifest and fail if generated files are stale",
    )
    args = parser.parse_args()
    stale = generate(check=args.check)
    if stale:
        for path in stale:
            print(f"stale generated architecture table: {path.relative_to(ROOT)}", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
